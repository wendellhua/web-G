/** 根据累计通关数解析当前所处阶段（0..2 -> 阶1, 3..7 -> 阶2, 8..15 -> 阶3, 16..24 -> 阶4, 25+ -> 阶5） */
export function resolveStageByClearedCount(clearedLevelsCount: number): StageConfig {
  const safe = Math.max(0, Math.floor(clearedLevelsCount));
  let matched = GAME_CONFIG.stages[0]!;
  for (const stage of GAME_CONFIG.stages) {
    if (safe >= stage.requiredTotalClearsToUnlock) {
      matched = stage;
    }
  }
  return matched;
}

/** 根据当前关卡号解析所属阶段（1..3 -> 阶1, 4..8 -> 阶2, 9..16 -> 阶3, 17..25 -> 阶4, 26+ -> 阶5） */
export function resolveStageByLevelNumber(levelNumber: number): StageConfig {
  const safe = Math.max(1, Math.floor(levelNumber));
  return resolveStageByClearedCount(safe - 1);
}

